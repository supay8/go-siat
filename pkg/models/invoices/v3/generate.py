def go_name(s):
    # Conserva la escritura exacta del campo XML en los tags.
    return s[0].upper() + s[1:]

def field_type(e):
    restriction = e.find('x:simpleType/x:restriction', ns)
    base = restriction.get('base') if restriction is not None else e.get('type', 'xs:string')
    typ = {'integer': 'int64', 'int': 'int64', 'string': 'string', 'decimal': 'decimal.Decimal', 'dateTime': 'Time'}[base.split(':')[-1]]
    return f'Optional[{typ}]' if e.get('nillable') == 'true' else typ

def validation(name, fields):
    lines = [f'func (v {name}) validarXSD() error {{\n']
    for e in fields:
        field = e.get('name')
        value = 'v.' + go_name(field)
        typ = field_type(e)
        optional = e.get('nillable') == 'true'
        if optional:
            lines.append(f'if {value}.Value != nil {{\n value := *{value}.Value\n')
            value = 'value'
            typ = typ[len('Optional['):-1]
        r = e.find('x:simpleType/x:restriction', ns)
        facets = {f.tag.split('}')[-1]: f.get('value') for f in r} if r is not None else {}
        if typ == 'string':
            minimum, maximum = facets.get('minLength', '0'), facets.get('maxLength', '0')
            lines.append(f'if err := validarTexto("{field}", {value}, {minimum}, {maximum}); err != nil {{ return err }}\n')
        elif typ in ('int64', 'decimal.Decimal'):
            number = f'decimal.NewFromInt({value})' if typ == 'int64' else value
            minimum = facets.get('minInclusive', facets.get('minExclusive', ''))
            maximum = facets.get('maxInclusive', '')
            exclusive = 'true' if 'minExclusive' in facets else 'false'
            lines.append(f'if err := validarNumero("{field}", {number}, {facets.get("totalDigits", "0")}, {facets.get("fractionDigits", "0") if typ == "decimal.Decimal" else "0"}, "{minimum}", "{maximum}", {exclusive}); err != nil {{ return err }}\n')
            if e.get('fixed') is not None:
                lines.append(f'if !{number}.Equal(decimal.RequireFromString("{e.get("fixed")}")) {{ return fmt.Errorf("{field}: valor fijo inválido") }}\n')
        if optional:
            lines.append('}\n')
    lines.append('return nil\n}\n')
    return ''.join(lines)

