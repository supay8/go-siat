"""Generate typed V3 SOAP requests, builders, ports and thin adapters.

Wire payloads reuse the existing contracts except the V3 package without cafc.
Preparation and validation remain handwritten; this file only emits repetitive plumbing.
"""
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parent
repo = root.parents[2]
domain = repo / 'internal/core/domain/siat/facturacion/v3'
domain.mkdir(parents=True, exist_ok=True)
module = 'github.com/supay8/go-siat'
# name, SOAP input element, payload, emission, category, extra validation
ops = [
 ('RecepcionFactura','SolicitudServicioRecepcionFactura','facturacion.SolicitudRecepcionFactura',1,'facturacion','recepcion'),
 ('AnulacionFactura','SolicitudServicioAnulacionFactura','facturacion.SolicitudAnulacion',1,'facturacion','anulacion'),
 ('ReversionAnulacionFactura','SolicitudServicioReversionAnulacionFactura','facturacion.SolicitudReversionAnulacion',1,'facturacion','cuf'),
 ('VerificacionEstadoFactura','SolicitudServicioVerificacionEstadoFactura','facturacion.SolicitudVerificacionEstado',1,'facturacion','cuf'),
 ('RecepcionPaqueteFactura','SolicitudServicioRecepcionPaquete','SolicitudPaquete',2,'facturacion','paquete'),
 ('ValidacionRecepcionPaqueteFactura','SolicitudServicioValidacionRecepcionPaquete','facturacion.SolicitudValidacionRecepcion',2,'facturacion','validacion'),
 ('RecepcionDocumentoAjuste','SolicitudServicioRecepcionDocumentoAjuste','facturacion.SolicitudRecepcionFactura',1,'documento_ajuste','recepcion'),
 ('AnulacionDocumentoAjuste','SolicitudServicioAnulacionDocumentoAjuste','facturacion.SolicitudAnulacion',1,'documento_ajuste','anulacion'),
 ('ReversionAnulacionDocumentoAjuste','SolicitudServicioReversionAnulacionDocumentoAjuste','facturacion.SolicitudReversionAnulacion',1,'documento_ajuste','cuf'),
 ('VerificacionEstadoDocumentoAjuste','SolicitudServicioVerificacionEstadoDocumentoAjuste','facturacion.SolicitudVerificacionEstado',1,'documento_ajuste','cuf'),
]
header = '// Code generated by pkg/models/v3/generate.py; DO NOT EDIT.\n'
d = [header, f'''package v3
import ("encoding/xml"; "fmt"; "strings"; "time";

 documents "{module}/internal/core/domain/documents/v3"; "{module}/internal/core/domain/siat/facturacion")
''']
p = [header, f'''package v3
import ("time";

 "{module}/internal/core/domain/datatype"; domain "{module}/internal/core/domain/siat/facturacion/v3"; "{module}/pkg/models"; invoices "{module}/pkg/models/invoices/v3")
''']
for name, element, payload, emission, category, kind in ops:
    method = name[0].lower()+name[1:]
    d.append(f'''type {name} struct {{
 XMLName xml.Name `xml:"ns:{method}"`
 Solicitud {payload} `xml:"{element}"`
 Preparado Preparacion `xml:"-" json:"-"`
}}
func (r *{name}) ValidarIdentidad(nit int64, sistema string, ambiente int) error {{ return validarIdentidad(r.Solicitud.SolicitudRecepcion,r.Preparado,nit,sistema,ambiente) }}
func (r *{name}) ValidarServicio(familia documents.Familia) error {{
 if err := validarServicio(r.Solicitud.SolicitudRecepcion,familia,{emission}); err != nil {{return err}}
''')
    if kind in ('cuf','anulacion'):
        d.append('if strings.TrimSpace(r.Solicitud.Cuf)=="" {return fmt.Errorf("CUF requerido")}\n')
    if kind == 'anulacion':
        d.append('if r.Solicitud.CodigoMotivo<=0 {return fmt.Errorf("motivo de anulación requerido")}\n')
    if kind == 'validacion':
        d.append('if strings.TrimSpace(r.Solicitud.CodigoRecepcion)=="" {return fmt.Errorf("código de recepción requerido")}\n')
    if kind in ('recepcion','paquete'):
        d.append('if time.Time(r.Solicitud.FechaEnvio).IsZero() {return fmt.Errorf("fecha de envío requerida")}\n')
        d.append(f'if err := validarPreparacion(r.Solicitud.SolicitudRecepcion,r.Preparado,r.Solicitud.Archivo,r.Solicitud.HashArchivo,{str(kind=="recepcion").lower()}); err != nil {{return err}}\n')
    if kind == 'paquete':
        d.append('if r.Solicitud.CantidadFacturas<1 || r.Solicitud.CantidadFacturas>500 || r.Solicitud.CodigoEvento<=0 {return fmt.Errorf("cantidad o evento de paquete inválidos")}\n')
    d.append('return nil\n}\n')
    p.append(f'''type {name} struct {{models.RequestWrapper[domain.{name}]}}
type {name}Builder struct {{request domain.{name}; sesion Sesion}}
func New{name}Builder() *{name}Builder {{ b:= &{name}Builder{{}}; b.request.Solicitud.CodigoModalidad=1; b.request.Solicitud.CodigoEmision={emission}; return b }}
func (b *{name}Builder) WithSesion(s Sesion) *{name}Builder {{ b.sesion=s; r:= &b.request.Solicitud; r.CodigoSucursal=s.Sucursal; r.CodigoPuntoVenta=s.POS; r.Cuis=s.CUIS; r.Cufd=s.CUFD; return b }}
func (b *{name}Builder) WithCodigoDocumentoSector(sector int) *{name}Builder {{ setSector(&b.request.Solicitud.SolicitudRecepcion,sector); return b }}
func (b *{name}Builder) Build() {name} {{ snapshot:=b.request; return {name}{{models.NewRequestWrapper(&snapshot)}} }}
''')
    fields = [('CodigoSucursal','int'),('CodigoPuntoVenta','int'),('Cuis','string'),('Cufd','string'),('CodigoModalidad','int'),('CodigoEmision','int'),('TipoFacturaDocumento','int'),('Nit','int64'),('CodigoSistema','string'),('CodigoAmbiente','int')]
    if kind in ('cuf','anulacion'): fields.append(('Cuf','string'))
    if kind=='anulacion': fields.append(('CodigoMotivo','int'))
    if kind=='validacion': fields.append(('CodigoRecepcion','string'))
    for field, typ in fields:
        p.append(f'func (b *{name}Builder) With{field}(value {typ}) *{name}Builder {{ b.request.Solicitud.{field}=value; return b }}\n')
    if kind in ('recepcion','paquete'):
        p.append(f'func (b *{name}Builder) WithFechaEnvio(value time.Time) *{name}Builder {{ b.request.Solicitud.FechaEnvio=datatype.NewTimeSiat(invoices.Time(value).Time()); return b }}\n')
    if kind=='recepcion':
        setter='WithDocumento' if category=='documento_ajuste' else 'WithFactura'
        p.append(f'''func (b *{name}Builder) {setter}(documento invoices.Documento, signer models.XMLSigner) error {{
 prepared,err:=prepararDocumento(documento,b.sesion,signer,{str(category=='documento_ajuste').lower()}); if err!=nil {{return err}}
 r:= &b.request.Solicitud
 if err:=aplicarDocumento(&r.SolicitudRecepcion,prepared.Info); err!=nil {{return err}}
 r.Archivo=prepared.Archivo; r.HashArchivo=prepared.Hash; b.request.Preparado=domain.Preparacion{{Info:prepared.Info,Hash:prepared.Hash,Sesion:b.sesion}}
 return nil
}}
''')
    if kind=='paquete':
        p.append(f'''func (b *{name}Builder) WithArchivoTarGz(archivo []byte, evento EventoPaquete) error {{
 prepared,err:=prepararPaquete(b.sesion,evento,archivo); if err!=nil {{return err}}
 r:= &b.request.Solicitud
 if err:=aplicarDocumento(&r.SolicitudRecepcion,prepared.Info); err!=nil {{return err}}
 r.Archivo=prepared.Archivo; r.HashArchivo=prepared.Hash; r.CantidadFacturas=prepared.Cantidad; r.CodigoEvento=evento.Codigo
 b.request.Preparado=domain.Preparacion{{Info:prepared.Info,Hash:prepared.Hash,Sesion:b.sesion}}
 return nil
}}
''')
(domain/'requests_generated.go').write_text(''.join(d))
(root/'requests_generated.go').write_text(''.join(p))

port=[header,'package ports\n',f'import ("context";\n\n models "{module}/pkg/models/v3")\n']
adapter=[header,'package services\n',f'import ("context";\n\n "{module}/internal/core/domain/siat/facturacion"; "{module}/internal/core/domain/siat/documento_ajuste"; "{module}/internal/core/domain/datatype/soap"; domain "{module}/internal/core/domain/siat/facturacion/v3"; models "{module}/pkg/models/v3"; "{module}/internal/core/ports")\n']
for category, interface in [('facturacion','FacturacionV3Service'),('documento_ajuste','DocumentoAjusteV3Service')]:
    struct='FacturacionV3ServiceImpl' if category=='facturacion' else 'DocumentoAjusteV3ServiceImpl'
    port.append(f'type {interface} interface {{\n')
    for name, _, _, _, cat, _ in ops:
        if cat!=category: continue
        port.append(f'{name}(context.Context,models.{name}) (*models.Respuesta[models.{name}Response],error)\n')
        adapter.append(f'''func (s *{struct}) {name}(ctx context.Context,req models.{name}) (*soap.EnvelopeResponse[domain.{name}Response],error) {{
 return performV3Request[domain.{name},domain.{name}Response](ctx,s.transport,req)
}}
''')
    comm='VerificarComunicacionFacturacion' if category=='facturacion' else 'VerificarComunicacionDocumentoAjuste'
    port.append(f'VerificarComunicacion(context.Context,models.{comm}) (*models.Respuesta[models.VerificarComunicacionResponse],error)\n}}\n')
    adapter.append(f'''func (s *{struct}) VerificarComunicacion(ctx context.Context,req models.{comm}) (*soap.EnvelopeResponse[domain.VerificarComunicacionResponse],error) {{
 return performSoapRequest[{category}.VerificarComunicacion,domain.VerificarComunicacionResponse](ctx,s.transport.httpClient,s.transport.url,s.transport.config,req)
}}
var _ ports.{interface} = (*{struct})(nil)
''')
    pth=root/'communication.go'
pth.write_text(header+f'''package v3
import ("{module}/pkg/models"; "{module}/internal/core/domain/siat/facturacion"; "{module}/internal/core/domain/siat/documento_ajuste")
type VerificarComunicacionFacturacion struct {{models.RequestWrapper[facturacion.VerificarComunicacion]}}
func NewVerificarComunicacionFacturacion() VerificarComunicacionFacturacion {{return VerificarComunicacionFacturacion{{models.NewRequestWrapper(&facturacion.VerificarComunicacion{{}})}}}}
type VerificarComunicacionDocumentoAjuste struct {{models.RequestWrapper[documento_ajuste.VerificarComunicacion]}}
func NewVerificarComunicacionDocumentoAjuste() VerificarComunicacionDocumentoAjuste {{return VerificarComunicacionDocumentoAjuste{{models.NewRequestWrapper(&documento_ajuste.VerificarComunicacion{{}})}}}}
''')

responses=[header,'package v3\n',f'import ("encoding/xml";\n\n "{module}/internal/core/domain/siat/facturacion"; "{module}/internal/core/domain/siat/common")\n',
 'type RespuestaRecepcion facturacion.RespuestaRecepcion\nfunc(r RespuestaRecepcion) IsSuccess() bool {return r.Transaccion}\nfunc(r RespuestaRecepcion) GetMessages() []common.MensajeServicio {return r.MensajesList}\n',
 'type RespuestaComunicacion facturacion.RespuestaComunicacion\nfunc(r RespuestaComunicacion) IsSuccess() bool {return r.Transaccion}\nfunc(r RespuestaComunicacion) GetMessages() []common.MensajeServicio {return r.MensajesList}\n',
 'type VerificarComunicacionResponse struct { XMLName xml.Name `xml:"verificarComunicacionResponse"`; Return RespuestaComunicacion `xml:"return"` }\n']
for name, _, _, _, _, _ in ops:
    method=name[0].lower()+name[1:]
    field='RespuestaRecepcionFactura' if name=='RecepcionDocumentoAjuste' else 'RespuestaServicioFacturacion'
    responses.append(f'type {name}Response struct {{ XMLName xml.Name `xml:"{method}Response"`; {field} RespuestaRecepcion `xml:"RespuestaServicioFacturacion"` }}\n')
(domain/'responses_generated.go').write_text(''.join(responses))
public_responses=[header,'package v3\n',f'import (domain "{module}/internal/core/domain/siat/facturacion/v3"; "{module}/internal/core/domain/datatype/soap")\n',
 'type Respuesta[T any] = soap.EnvelopeResponse[T]\n',
 'type RespuestaRecepcion = domain.RespuestaRecepcion\ntype RespuestaComunicacion = domain.RespuestaComunicacion\ntype VerificarComunicacionResponse = domain.VerificarComunicacionResponse\n']
for name, _, _, _, _, _ in ops:
    public_responses.append(f'type {name}Response = domain.{name}Response\n')
(root/'responses_generated.go').write_text(''.join(public_responses))
subprocess.run(['gofmt','-w',str(root/'responses_generated.go')],check=True)

subprocess.run(['gofmt','-w',str(domain/'responses_generated.go')],check=True)

(repo/'internal/core/ports/siat_v3_port.go').write_text(''.join(port))
(repo/'internal/adapter/services/siat_v3_methods_generated.go').write_text(''.join(adapter))
subprocess.run(['gofmt','-w',str(domain/'requests_generated.go'),str(root/'requests_generated.go'),str(pth),str(repo/'internal/core/ports/siat_v3_port.go'),str(repo/'internal/adapter/services/siat_v3_methods_generated.go')],check=True)
